// Testumgebung (Node): localStorage nachbilden. BroadcastChannel und crypto bringt Node 22 mit.
class SpeicherAblage implements Storage {
  private m = new Map<string, string>();
  get length() {
    return this.m.size;
  }
  clear() {
    this.m.clear();
  }
  getItem(k: string) {
    return this.m.has(k) ? this.m.get(k)! : null;
  }
  key(i: number) {
    return [...this.m.keys()][i] ?? null;
  }
  removeItem(k: string) {
    this.m.delete(k);
  }
  setItem(k: string, v: string) {
    this.m.set(k, String(v));
  }
}

(globalThis as { localStorage?: Storage }).localStorage = new SpeicherAblage();
export { SpeicherAblage };
